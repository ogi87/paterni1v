    public void setValue(Object value) {
        clearError();
        if (value == null) {
            buttonGroupGender.clearSelection();
            return;
        }
        String s = value.toString().trim();
        if ("Muški".equalsIgnoreCase(s) || "Muski".equalsIgnoreCase(s) || "M".equalsIgnoreCase(s)) {
            rbMale.setSelected(true);
        } else if ("Ženski".equalsIgnoreCase(s) || "Zenski".equalsIgnoreCase(s) || "Ž".equalsIgnoreCase(s) || "Z".equalsIgnoreCase(s)) {
            rbFemale.setSelected(true);
        } else {
            buttonGroupGender.clearSelection();
        }
    }

    @Override
    public Object getValue() throws Exception {
        clearError();
        if (rbMale.isSelected()) {
            return "Muški";
        } else if (rbFemale.isSelected()) {
            return "Ženski";
        } else {
            errorText.setText("Morate odabrati pol");
            throw new Exception("Morate odabrati pol");
        }
    }

